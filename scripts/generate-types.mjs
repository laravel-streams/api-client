#!/usr/bin/env node
/**
 * Build TypeScript entry types from streams:schema output.
 *
 * Reads every {id}.schema.json file written by Laravel's `streams:schema`
 * command (streams/sdk) and turns it into one entry interface per stream,
 * plus a `StreamId` union and a `StreamEntryMap` keyed by stream id.
 *
 * Usage:
 *   node scripts/generate-types.mjs [schemaDir] [outFile]
 *
 * Defaults: schemaDir = <repo>/schemas, outFile = <repo>/types/entries.generated.d.ts
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = path.resolve(process.argv[2] ?? path.join(rootDir, 'schemas'));
const outFile = path.resolve(process.argv[3] ?? path.join(rootDir, 'types', 'entries.generated.d.ts'));

function pascalCase(id) {
    return id
        .split(/[-_]+/g)
        .filter(Boolean)
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join('');
}

/**
 * Turn a JSON Schema property node into a TypeScript type expression.
 */
function schemaPropertyToTs(prop, depth = 0) {
    if (prop === null || typeof prop !== 'object') {
        return 'unknown';
    }

    let base;

    if (Array.isArray(prop.type)) {
        base = prop.type.map((type) => schemaPropertyToTs({ ...prop, type, nullable: false }, depth)).join(' | ');
    } else if (Array.isArray(prop.enum) && prop.enum.length > 0) {
        base = prop.enum.map((value) => JSON.stringify(value)).join(' | ');
    } else {
        switch (prop.type) {
            case 'string':
                base = 'string';
                break;
            case 'integer':
            case 'number':
                base = 'number';
                break;
            case 'boolean':
                base = 'boolean';
                break;
            case 'array':
                base = prop.items ? `${schemaPropertyToTs(prop.items, depth + 1)}[]` : 'unknown[]';
                break;
            case 'object':
                base = prop.properties ? objectSchemaToTs(prop, depth + 1) : 'Record<string, unknown>';
                break;
            default:
                base = 'unknown';
        }
    }

    return prop.nullable === true ? `${base} | null` : base;
}

function objectSchemaToTs(schema, depth) {
    const required = new Set(Array.isArray(schema.required) ? schema.required : []);
    const entries = Object.entries(schema.properties ?? {});

    if (entries.length === 0) {
        return 'Record<string, unknown>';
    }

    const pad = '    '.repeat(depth + 1);
    const close = '    '.repeat(depth);
    const lines = entries.map(([key, prop]) => {
        const optional = required.has(key) ? '' : '?';
        return `${pad}${JSON.stringify(key)}${optional}: ${schemaPropertyToTs(prop, depth + 1)};`;
    });

    return `{\n${lines.join('\n')}\n${close}}`;
}

async function main() {
    const files = (await readdir(schemaDir)).filter((name) => name.endsWith('.schema.json'));
    if (files.length === 0) {
        throw new Error(`No *.schema.json files found in ${schemaDir}`);
    }

    files.sort();

    const blocks = [];
    const mapLines = [];

    for (const file of files) {
        const streamId = file.replace(/\.schema\.json$/, '');
        const schema = JSON.parse(await readFile(path.join(schemaDir, file), 'utf8'));
        const name = `${pascalCase(streamId)}Entry`;
        blocks.push(`export interface ${name} ${objectSchemaToTs(schema, 0)}`);
        mapLines.push(`    ${JSON.stringify(streamId)}: ${name};`);
    }

    const header =
        '// Generated by scripts/generate-types.mjs from streams:schema output.\n' +
        '// Do not edit by hand; run `npm run types:generate` instead.\n\n';

    const streamIdUnion = files.map((file) => JSON.stringify(file.replace(/\.schema\.json$/, ''))).join(' | ');

    const contents =
        header +
        blocks.join('\n\n') +
        '\n\n' +
        `export type StreamId = ${streamIdUnion};\n\n` +
        'export interface StreamEntryMap {\n' +
        mapLines.join('\n') +
        '\n}\n';

    await writeFile(outFile, contents, 'utf8');
    console.log(`Wrote ${outFile} (${files.length} streams)`);
}

main().catch((error) => {
    console.error(error);
    process.exit(1);
});
